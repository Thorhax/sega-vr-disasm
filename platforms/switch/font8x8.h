inline void draw_char(SDL_Renderer* ren, int x, int y, char ch, uint8_t r, uint8_t g, uint8_t b, uint8_t a, int scale) {
    if (ch < 32 || ch > 126) ch = '?';
    const uint8_t* glyph = g_font8x8[ch - 32];
    SDL_SetRenderDrawColor(ren, r, g, b, a);
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (bits & (0x80 >> col)) {
                SDL_Rect rc{x + col * scale, y + row * scale, scale, scale};
                SDL_RenderFillRect(ren, &rc);
            }
        }
    }
}

inline void draw_text(SDL_Renderer* ren, int x, int y, const char* str, uint8_t r, uint8_t g, uint8_t b, int scale, bool shadow = true) {
    int cur_x = x;
    while (*str) {
        if (*str == '\n') {
            cur_x = x;
            y += 9 * scale;
        } else {
            if (shadow) {
                draw_char(ren, cur_x + scale, y + scale, *str, 0, 0, 0, 200, scale);
            }
            draw_char(ren, cur_x, y, *str, r, g, b, 255, scale);
            cur_x += 8 * scale;
        }
        str++;
    }
}

inline int text_width(const char* str, int scale) {
    int max_w = 0, cur_w = 0;
    while (*str) {
        if (*str == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
        } else {
            cur_w += 8 * scale;
        }
        str++;
    }
    return (cur_w > max_w) ? cur_w : max_w;
}

